def _find_raw_row(uni_key, name):
    for row in RAW[uni_key]:
        if row[0] == name:
            return row
    raise KeyError(f"لا يوجد صف باسم '{name}' بجامعة '{uni_key}' جوا RAW")



# ترتيب العرض الموحّد للفروع بمصفوفة track بكل تخصص. '-' و'علمي-أدبي' بقيم RAW
# لسا بيعنوا "علمي وأدبي مع بعض" (الحالة الأكثر شيوعاً بأقصى/الإسلامية/فلسطين).
# فروع تانية (صناعي، زراعي، شرعي) بتتفكّ من نص مفصول بـ"،" (زي بيانات الأزهر
# الجديدة اللي بتسمح بأكتر من فرعين). "جميع الفروع" بتضل نص حرفي واحد بدون
# تفكيك لأنه ما عندنا قائمة رسمية مؤكدة بكل الفروع المقصودة فيها.
TRACK_DISPLAY_ORDER = ('علمي', 'أدبي', 'صناعي', 'زراعي', 'شرعي', 'جميع الفروع')


def _parse_tracks(track):
    if track in ('-', 'علمي-أدبي'):
        return ['علمي', 'أدبي']
    if track == 'جميع الفروع':
        return ['جميع الفروع']
    return [t.strip() for t in track.split('،') if t.strip()]


def build_admission(sources):
    """يبني مصفوفة admission وقائمة الفروع الموحدة لتخصص معين من مصادره الخام."""
    admission = []
    tracks = set()

    for uni_key, raw_name in sources:
        _, track, min_gpa, competitive_gpa, fee = _find_raw_row(uni_key, raw_name)
        tracks.update(_parse_tracks(track))

        entry = {
            'university': UNIVERSITY_NAMES[uni_key],
            'minGpa': min_gpa,
            'competitiveGpa': competitive_gpa if competitive_gpa is not None else min_gpa,
            'year': ADMISSION_YEAR,
            'verified': True,
        }
        if fee is not None:
            entry['feePerCreditHour'] = fee
        admission.append(entry)

    ordered_tracks = [t for t in TRACK_DISPLAY_ORDER if t in tracks]
    return admission, ordered_tracks


def build():
    result = []
    seen_ids = set()

    for major in MAJORS:
        if major['id'] in seen_ids:
            raise ValueError(f"id مكرر: {major['id']}")
        seen_ids.add(major['id'])

        admission, track = build_admission(major['sources'])
        if not track:
            raise ValueError(f"تخصص بدون فرع: {major['id']}")

        entry = {
            'id': major['id'],
            'name': major['name'],
            'faculty': major['faculty'],
            'track': track,
            'duration': major['duration'],
            'admission': admission,
            'skillsNeeded': major['skillsNeeded'],
            'skillsToLearnNow': major['skillsToLearnNow'],
            'careers': major['careers'],
            'relatedMajors': major['relatedMajors'],
        }
        # حقول اختيارية لصفحة المقارنة — بتنضاف لاحقاً لكل تخصص لما يتوفر مصدر بشري موثوق لها.
        # لو مش موجودة بعنصر MAJORS، بتنغاب تماماً من majors.json (مش null) عشان الواجهة تعرف تميّز
        # "لسا ما انكتبت" عن "قيمتها صفر/فاضية".
        for optional_key in ('difficultyScore', 'marketDemand', 'coreSubjects'):
            if optional_key in major:
                entry[optional_key] = major[optional_key]
        result.append(entry)

    out_path = Path(__file__).resolve().parent.parent / 'src' / 'data' / 'majors.json'
    out_path.write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + '\n',
        encoding='utf-8',
    )
    print(f"✓ تم بناء {len(result)} تخصص → {out_path}")


if __name__ == '__main__':
    build()
